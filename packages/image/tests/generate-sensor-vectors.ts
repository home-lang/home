// Numeric scalar reference of Picamera2's NumPy COMP1 equations, never Python.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
export function referenceWord(word: number): number[] {
  const m = word % 4,
    base = (word >>> 2) % 512,
    delta = ((word >>> 11) % 128) - 64
  let q: number[], curve: (x: number) => number
  if (m === 3) {
    const pair = (half: number) => [
      (half % 16) + 16 * Math.floor(Math.floor(half / 256) / 11),
      Math.floor(half / 16) % 176,
    ]
    q = [...pair((word >>> 2) % 32768), ...pair(word >>> 17)]
    curve = (x) => Math.max(x * 256, (x - 47) * 512)
  } else {
    const low = m * base < 768,
      a = low ? Math.max(base, base - delta) : base,
      b = low ? Math.max(base, base + delta) : delta + 448,
      neighbor = (v: number, residual: number) =>
        Math.min(1536 / 2 ** m, Math.max(0, v - 64)) + residual
    q = [neighbor(a, (word >>> 18) % 128), a, b, neighbor(b, word >>> 25)]
    curve = (x) => Math.max(x * 16, (x - 160) * 32, m * x * 64)
  }
  return q.map((v) => Math.min(65535, Math.max(0, curve(v) + 2048)))
}
if (import.meta.main) {
  const words = new Set([
    0, 1, 2, 3, 0xffffffff, 0xaaaaaaaa, 0x55555555, 0x80000000,
  ])
  for (const m of [0, 1, 2, 3])
    for (const base of [0, 63, 64, 159, 160, 255, 256, 383, 384, 447, 448, 511])
      for (const delta of [0, 63, 64, 127])
        words.add(
          (m + base * 4 + delta * 2048 + 127 * 2 ** 18 + 127 * 2 ** 25) >>> 0,
        )
  let seed = 0x7ac0ffee
  for (let i = 0; i < 256; i++) {
    seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0
    words.add(seed)
  }
  const lines = [...words].map(
    (w) =>
      `    .{ .word = 0x${w.toString(16)}, .expected = .{ ${referenceWord(w).join(', ')} } },`,
  )
  writeFileSync(
    fileURLToPath(
      new URL('../src/ops/sensor_raw_vectors.zig', import.meta.url),
    ),
    '// Generated by packages/image/tests/generate-sensor-vectors.ts.\n// Scalar reference of pinned Picamera2 equations; see sensor_raw.zig attribution.\npub const vectors = [_]struct { word: u32, expected: [4]u16 }{\n' +
      lines.join('\n') +
      '\n};\n',
  )
}
