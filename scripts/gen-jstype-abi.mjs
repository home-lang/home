#!/usr/bin/env node
// Regenerates `packages/runtime/src/native/jstype_abi.cpp`, the build-time
// guard that keeps Home's `JSType.zig` and the linked WebKit describing the
// same JSC cell-type table.
//
// Zig reads `JSC::JSCell::type()` as a plain enum byte. When the two tables
// disagree the link still succeeds and every type test silently reclassifies
// values instead (a Promise read as a Map), so the guard has to cover the
// whole enum rather than a sample of it. WebKit derives `enum JSType` from
// `FOR_EACH_JS_TYPE` in declaration order with no explicit values, which is
// what makes the header's macro list the authority for every member's number.
//
// This script also verifies the Zig side before emitting: `JSType.zig` must
// declare the same number of members, in the same order, with positional
// values. A mismatch is reported instead of being written out, because the
// generated asserts would otherwise encode the drift they exist to catch.
//
// Usage:  node scripts/gen-jstype-abi.mjs
//   HOME_BUN_WEBKIT_LIB overrides the pinned WebKit whose headers are read;
//   it takes the same value the build uses (see `linkBunNative` in build.zig).

import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";

// Keep in lockstep with `bun_webkit_version` in build.zig.
const WEBKIT_VERSION = "cd821fecca0d39c8";
const DEFAULT_WEBKIT_LIB = join(homedir(), ".bun", "build-cache", `webkit-${WEBKIT_VERSION}-macos-arm64`, "lib");

const REPO = resolve(dirname(new URL(import.meta.url).pathname), "..");
const ZIG_SOURCE = join(REPO, "packages/runtime/src/jsc/JSType.zig");
const OUTPUT = join(REPO, "packages/runtime/src/native/jstype_abi.cpp");

const webkitLib = process.env.HOME_BUN_WEBKIT_LIB || DEFAULT_WEBKIT_LIB;
const headerPath = join(dirname(webkitLib), "include", "JavaScriptCore", "JSType.h");

let header;
try {
  header = readFileSync(headerPath, "utf8");
} catch {
  console.error(`error: cannot read ${headerPath}`);
  console.error(`       build Bun at the pinned native artifact SHA (see home-lang/home#66) or set HOME_BUN_WEBKIT_LIB.`);
  process.exit(1);
}

// `FOR_EACH_JS_TYPE(macro)` lists every member once, in enum order.
const macroList = header.split("#define FOR_EACH_JS_TYPE(macro)")[1]?.split("enum JSType")[0];
if (!macroList) {
  console.error(`error: ${headerPath} has no FOR_EACH_JS_TYPE list; WebKit's JSType.h layout changed`);
  process.exit(1);
}
const headerNames = [...macroList.matchAll(/^\s+macro\(([A-Za-z0-9_]+),/gm)].map((m) => m[1]);

// Home's enum carries the numbers Zig compiles against.
const zigBody = readFileSync(ZIG_SOURCE, "utf8").split("pub const JSType = enum(u8) {")[1];
if (!zigBody) {
  console.error(`error: ${ZIG_SOURCE} has no 'pub const JSType = enum(u8)' declaration`);
  process.exit(1);
}
const zigMembers = [...zigBody.matchAll(/^ {4}([A-Za-z_][A-Za-z0-9_]*) = (\d+),$/gm)].map((m) => [m[1], Number(m[2])]);

const problems = [];
if (zigMembers.length !== headerNames.length) {
  problems.push(`member count: JSType.zig has ${zigMembers.length}, ${headerPath} has ${headerNames.length}`);
}
for (const [index, [name, value]] of zigMembers.entries()) {
  if (value !== index) problems.push(`JSType.${name} = ${value} is not its declaration position ${index}`);
}
if (problems.length > 0) {
  console.error("error: JSType.zig does not match the linked WebKit; not writing the guard:");
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}

const width = Math.max(...headerNames.map((n) => n.length));
const asserts = headerNames
  .map((headerName, index) => {
    const padding = " ".repeat(width - headerName.length);
    return `static_assert(JSC::${headerName} == ${index});${padding}${" ".repeat(4 - String(index).length)}// JSType.${zigMembers[index][0]}`;
  })
  .join("\n");

writeFileSync(
  OUTPUT,
  `// Generated by scripts/gen-jstype-abi.mjs — do not edit by hand.
//
// Zig reads JSC::JSCell::type() as an enum byte, so a table that disagrees
// with the linked WebKit does not fail to link: it silently reclassifies
// values (a Promise read as a Map). Every member of Home's JSType.zig is
// asserted here, because a member that is merely unasserted is a member that
// can drift undetected when the WebKit pin moves.
//
// WebKit ${WEBKIT_VERSION} (Bun's pinned WEBKIT_VERSION; see build.zig).
// Regenerate after moving that pin:  node scripts/gen-jstype-abi.mjs
#include <JavaScriptCore/JSType.h>

${asserts}
`,
);

console.log(`wrote ${OUTPUT} (${headerNames.length} members, WebKit ${WEBKIT_VERSION})`);
