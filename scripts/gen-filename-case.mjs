import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

// The pinned TypeScript 7.0.2 native reference uses Go 1.26.4's simple
// Unicode 15.0 mappings, not ECMAScript full-string casing.
const sourceURL = "https://raw.githubusercontent.com/golang/go/go1.26.4/src/unicode/tables.go";
const expectedSHA256 = "6a88d48746c4b2c471cc04ae40559694b734770212e6f5ea5f1962adb0c0bdb1";
const source = process.argv[2] ? readFileSync(process.argv[2], "utf8") : await (async () => {
  const response = await fetch(sourceURL);
  if (!response.ok) throw new Error(`Unicode source download failed: ${response.status}`);
  return response.text();
})();
if (createHash("sha256").update(source).digest("hex") !== expectedSHA256) throw new Error("Unicode source checksum differs");
if (!source.includes('const Version = "15.0.0"')) throw new Error("Unicode source version differs");
const block = source.match(/var _CaseRanges = \[\]CaseRange\{\n([\s\S]*?)\n\}/)?.[1];
if (!block) throw new Error("Unicode case ranges missing");
const rows = [];
let previous = -1;
for (const line of block.split("\n")) {
  if (!line.trim()) continue;
  const match = line.match(/^\s*\{(0x[0-9A-F]+), (0x[0-9A-F]+), d\{(-?\d+|UpperLower), (-?\d+|UpperLower), (-?\d+|UpperLower)\}\},$/);
  if (!match) throw new Error(`Unrecognized Unicode range: ${line}`);
  const [, lo, hi, upper, lower, title] = match;
  if (Number(lo) <= previous || Number(hi) < Number(lo)) throw new Error("Unicode ranges overlap or are unsorted");
  previous = Number(hi);
  const alternating = upper === "UpperLower";
  if ([upper, lower, title].some(value => value === "UpperLower") && ![upper, lower, title].every(value => value === "UpperLower")) throw new Error("Mixed alternating range");
  rows.push(`    .{ .lo = ${lo}, .hi = ${hi}, .upper = ${alternating ? 0 : upper}, .lower = ${alternating ? 0 : lower}, .alternating = ${alternating} },`);
}
if (rows.length < 300) throw new Error("Unicode range table is incomplete");
const output = [
  "// Copyright 2009 The Go Authors. See filename_case_data.LICENSE.",
  "// Generated by scripts/gen-filename-case.mjs. DO NOT EDIT.",
  `// Source: ${sourceURL}`,
  `// SHA256: ${expectedSHA256}`,
  '// Unicode 15.0.0 simple case mappings. Full-string casing is separate.',
  "pub const Range = struct { lo: u21, hi: u21, upper: i32, lower: i32, alternating: bool };",
  "pub const ranges = [_]Range{",
  ...rows,
  "};",
  "",
].join("\n");
writeFileSync("packages/ts_resolver/src/filename_case_data.zig", output);
console.log(`Generated ${rows.length} simple Unicode case ranges`);
